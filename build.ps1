# build.ps1 - fills in the parts of the site that come from content/, partials/ and templates/.
#
# Run it after changing anything in those folders:
#   powershell -ExecutionPolicy Bypass -File build.ps1
#
# What it does:
#   1. Writes one page per active product: shop/<slug>/index.html (from templates/product.html).
#      Removes the generated page of a product that is no longer active.
#   2. Refreshes every <!-- BUILD:name --> ... <!-- /BUILD:name --> region in every page
#      (header, footer, shop grid, home shop teaser, shipping rate, form key, logos).
#   3. Lists anything still marked ASK JOSH or missing (payment links, form key).
#
# The output is plain HTML that is committed to the repo, so the live site needs no build step.

$ErrorActionPreference = 'Stop'
$Root = $PSScriptRoot
$Utf8 = New-Object System.Text.UTF8Encoding($false)
$Inv = [Globalization.CultureInfo]::InvariantCulture
$Warnings = New-Object System.Collections.Generic.List[string]
$GeneratedMarker = 'GENERATED by build.ps1'

function Read-Text([string]$path) { [IO.File]::ReadAllText($path, $Utf8) }
function Write-Text([string]$path, [string]$text) {
  $dir = Split-Path -Parent $path
  if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir | Out-Null }
  [IO.File]::WriteAllText($path, $text, $Utf8)
}
function Read-Json([string]$path) { Read-Text $path | ConvertFrom-Json }
function Enc($s) { [Net.WebUtility]::HtmlEncode([string]$s) }
function Money($n) { '$' + ([double]$n).ToString('0.00', $Inv) }
function Is-Ask($s) { [string]$s -match 'ASK[ _]JOSH' }

# Encodes text and highlights any ASK JOSH marker so it can't be missed on the page.
function Show($s) {
  $html = Enc ([string]$s -replace 'ASK_JOSH', 'ASK JOSH')
  [regex]::Replace($html, 'ASK JOSH( to review:)?', { param($m) '<mark class="ask">' + $m.Value + '</mark>' })
}

function Fill([string]$template, $tokens) {
  foreach ($k in $tokens.Keys) { $template = $template.Replace('{{' + $k + '}}', [string]$tokens[$k]) }
  $template
}

# Replaces the inside of every <!-- BUILD:name --> ... <!-- /BUILD:name --> pair.
function Set-Region([string]$html, [string]$name, [string]$content) {
  $open = "<!-- BUILD:$name -->"
  $close = "<!-- /BUILD:$name -->"
  $sb = New-Object System.Text.StringBuilder
  $pos = 0
  while ($true) {
    $start = $html.IndexOf($open, $pos)
    if ($start -lt 0) { break }
    $end = $html.IndexOf($close, $start)
    if ($end -lt 0) { throw "Missing $close" }
    [void]$sb.Append($html.Substring($pos, $start - $pos)).Append($open).Append("`n").Append($content).Append("`n").Append($close)
    $pos = $end + $close.Length
  }
  [void]$sb.Append($html.Substring($pos))
  $sb.ToString()
}

function Svg-Inline([string]$file) {
  (Read-Text (Join-Path $Root "assets/logo/$file")) -replace '<\?xml[^>]*\?>\s*', '' | ForEach-Object { $_.Trim() }
}

# ---------------------------------------------------------------- site data

$site = Read-Json (Join-Path $Root 'content/site.json')
$year = (Get-Date).Year
$domainUrl = "https://$($site.domain)"

$promoOn = [bool]$site.promoBanner.enabled
$promoHtml = ''
if ($promoOn) { $promoHtml = '<p class="promo">' + (Enc $site.promoBanner.text) + '</p>' }

# Shop switch (content/site.json -> shopEnabled). Off: no Shop links, no product pages,
# no home teaser, and the remaining /shop/ pages are marked noindex. Missing counts as on.
$shopOn = ($null -eq $site.shopEnabled) -or ($site.shopEnabled -eq $true)
$shopLink = ''
if ($shopOn) { $shopLink = '        <li><a href="/shop/">Shop</a></li>' }

$logo1 = Svg-Inline 'option-1-nameplate.svg'
$tokens = [ordered]@{
  shopLink  = $shopLink
  siteName  = Enc $site.siteName
  legalName = Enc $site.legalName
  location  = Enc $site.location
  email     = Enc $site.publicEmail
  year      = $year
  promo     = $promoHtml
  logo      = $logo1
}
$partials = @{}
foreach ($p in 'head', 'header', 'shop-header', 'footer', 'shop-footer', 'privacy-shop') {
  $partials[$p] = Fill (Read-Text (Join-Path $Root "partials/$p.html")) $tokens
}

if ([string]$site.web3formsAccessKey -match '^REPLACE') {
  $Warnings.Add('content/site.json: web3formsAccessKey is still the placeholder; the quote form will not send.')
}

# ---------------------------------------------------------------- products

$productDir = Join-Path $Root 'content/products'
$index = Read-Json (Join-Path $productDir 'index.json')
$reserved = 'shipping', 'returns', 'thank-you'
$products = @()
foreach ($f in $index.products) {
  $path = Join-Path $productDir $f
  if (-not (Test-Path $path)) { throw "content/products/index.json lists $f, but that file doesn't exist." }
  $p = Read-Json $path
  if ($p.slug -notmatch '^[a-z0-9]+(-[a-z0-9]+)*$') { throw "${f}: slug '$($p.slug)' must be lowercase letters, numbers and dashes." }
  if ($reserved -contains $p.slug) { throw "${f}: slug '$($p.slug)' is reserved for a shop page." }
  $p | Add-Member -NotePropertyName _file -NotePropertyValue $f
  $products += $p
}
Get-ChildItem $productDir -Filter *.json | Where-Object { $_.Name -ne 'index.json' -and $index.products -notcontains $_.Name } | ForEach-Object {
  $Warnings.Add("content/products/$($_.Name) is not listed in index.json, so it is ignored.")
}
$active = @($products | Where-Object { $_.active -eq $true })

function Photo-Html($photo, [string]$cls, [bool]$lazy) {
  $label = [string]$photo.alt -replace '^PHOTO:\s*', ''
  if ($photo.file -and -not $photo.placeholder) {
    $loading = ''
    if ($lazy) { $loading = ' loading="lazy"' }
    return "<img class=""photo"" src=""/assets/photos/$(Enc $photo.file)"" alt=""$(Enc $label)""$loading>"
  }
  $l = Enc $label
  "<!-- PHOTO: $l (product photo: set ""file"" and ""placeholder"": false in the product JSON) --><div class=""ph $cls"" role=""img"" aria-label=""Photo placeholder: $l""><span>PHOTO: $l</span></div>"
}

function First-Photo($p) {
  if ($p.photos -and $p.photos.Count -gt 0) { return $p.photos[0] }
  [pscustomobject]@{ file = ''; alt = "PHOTO: $($p.name)"; placeholder = $true }
}

function Availability($p) {
  switch ([string]$p.availability) {
    'out_of_stock' { 'OutOfStock' }
    'preorder' { 'PreOrder' }
    default { 'InStock' }
  }
}

$template = Read-Text (Join-Path $Root 'templates/product.html')
foreach ($p in $products) {
  $out = Join-Path $Root "shop/$($p.slug)/index.html"
  if (-not $shopOn -or $p.active -ne $true) {
    if ((Test-Path $out) -and ((Read-Text $out).Contains($GeneratedMarker))) {
      Remove-Item $out
      $dir = Split-Path -Parent $out
      if (-not (Get-ChildItem $dir -Force)) { Remove-Item $dir }
      Write-Host "Removed product page shop/$($p.slug)/ (inactive, or the shop is off)"
    }
    continue
  }

  $f = $p._file
  $url = "$domainUrl/shop/$($p.slug)/"

  # Gallery: first photo large, the rest as thumbnails.
  $gallery = ''
  $photos = @($p.photos)
  if ($photos.Count -eq 0) { $photos = @(First-Photo $p) }
  $gallery += '<div class="gallery-main">' + (Photo-Html $photos[0] 'ph-4x3' $false) + '</div>'
  if ($photos.Count -gt 1) {
    $gallery += "`n      <div class=""gallery-thumbs"">"
    foreach ($ph in $photos[1..($photos.Count - 1)]) { $gallery += (Photo-Html $ph 'ph-1x1' $true) }
    $gallery += '</div>'
  }

  $fitsBlock = ''
  if ($p.fitsLine) { $fitsBlock += '<p class="fits">' + (Enc $p.fitsLine) + '</p>' }
  if ($p.trademarkNote) { $fitsBlock += "`n      <p class=""tm-note"">" + (Enc $p.trademarkNote) + '</p>' }

  $avail = Availability $p
  if ($avail -eq 'OutOfStock') {
    $buy = '<button class="btn" type="button" disabled>Sold out</button>'
  } elseif ($p.paymentLink) {
    if ($p.paymentLink -notmatch '^https://buy\.stripe\.com/') { $Warnings.Add("${f}: paymentLink doesn't start with https://buy.stripe.com/ - check it.") }
    $buy = "<a class=""btn"" href=""$(Enc $p.paymentLink)"">Buy now</a>"
  } else {
    $buy = '<button class="btn" type="button" disabled>Coming soon</button>'
    $Warnings.Add("${f}: no paymentLink yet, so the Buy button shows 'Coming soon'.")
  }

  if ($promoOn) { $shipLine = Enc $site.promoBanner.text }
  else { $shipLine = (Money $site.shopShippingFlat) + ' flat shipping. Orders by noon Central ship same business day.' }

  $rows = foreach ($prop in $p.specs.PSObject.Properties) {
    "          <tr><th scope=""row"">$(Enc $prop.Name)</th><td>$(Show $prop.Value)</td></tr>"
  }

  # schema.org Product data for Google Search and Shopping.
  $offer = [ordered]@{
    '@type'         = 'Offer'
    price           = ([double]$p.price).ToString('0.00', $Inv)
    priceCurrency   = [string]$p.currency
    availability    = "https://schema.org/$avail"
    url             = $url
    shippingDetails = [ordered]@{
      '@type'             = 'OfferShippingDetails'
      shippingRate        = [ordered]@{ '@type' = 'MonetaryAmount'; value = [double]$site.shopShippingFlat; currency = 'USD' }
      shippingDestination = [ordered]@{ '@type' = 'DefinedRegion'; addressCountry = 'US' }
    }
    hasMerchantReturnPolicy = [ordered]@{
      '@type'              = 'MerchantReturnPolicy'
      applicableCountry    = 'US'
      returnPolicyCategory = 'https://schema.org/MerchantReturnNotPermitted'
    }
  }
  $ld = [ordered]@{
    '@context'  = 'https://schema.org'
    '@type'     = 'Product'
    name        = [string]$p.name
    description = [string]$p.shortDescription
  }
  $images = @($p.photos | Where-Object { $_.file -and -not $_.placeholder } | ForEach-Object { "$domainUrl/assets/photos/$($_.file)" })
  if ($images.Count -gt 0) { $ld.image = $images } else { $Warnings.Add("${f}: no real photos yet (Google Shopping needs at least one).") }
  if ($p.sku -and -not (Is-Ask $p.sku)) { $ld.sku = [string]$p.sku }
  $ld.brand = [ordered]@{ '@type' = 'Brand'; name = [string]$site.siteName }
  $ld.offers = $offer

  $titleText = $p.name
  if ($p.fitsLine) { $titleText = "$($p.name), $($p.fitsLine)" }

  $page = Fill $template ([ordered]@{
    sourceFile       = Enc $f
    titleText        = Enc $titleText
    metaDescription  = Enc $p.shortDescription
    url              = Enc $url
    jsonld           = ($ld | ConvertTo-Json -Depth 10)
    gallery          = $gallery
    name             = Enc $p.name
    fitsBlock        = $fitsBlock
    price            = Money $p.price
    shortDescription = Show $p.shortDescription
    buyButton        = $buy
    shippingLine     = $shipLine
    description      = Show $p.description
    specRows         = ($rows -join "`n")
  })
  Write-Text $out $page

  # Collect ASK JOSH items left in this product file.
  foreach ($prop in $p.PSObject.Properties) {
    if ($prop.Value -is [string] -and (Is-Ask $prop.Value)) { $Warnings.Add("${f}: $($prop.Name) is marked ASK JOSH.") }
  }
  foreach ($prop in $p.specs.PSObject.Properties) {
    if (Is-Ask $prop.Value) { $Warnings.Add("${f}: specs.$($prop.Name) is marked ASK JOSH.") }
  }
}

# ---------------------------------------------------------------- shared regions

function Card-Html($p) {
  $href = "/shop/$($p.slug)/"
  $photo = Photo-Html (First-Photo $p) 'ph-4x3' $true
@"
<article class="product-card">
  <a href="$href" tabindex="-1" aria-hidden="true">$photo</a>
  <h3><a href="$href">$(Enc $p.name)</a></h3>
  <p class="price">$(Money $p.price)</p>
  <a class="btn btn-small" href="$href" aria-label="View $(Enc $p.name)">View</a>
</article>
"@
}

if (-not $shopOn) {
  $grid = '<p>The shop opens soon.</p>'
  $homeShop = ''
} elseif ($active.Count -gt 0) {
  $grid ='<div class="product-grid">' + "`n" + (($active | ForEach-Object { Card-Html $_ }) -join "`n") + '</div>'
  $p = $active[0]
  $href = "/shop/$($p.slug)/"
  $homeShop = @"
<section class="section" aria-labelledby="from-the-shop">
  <div class="wrap shop-teaser">
    <a href="$href" tabindex="-1" aria-hidden="true">$(Photo-Html (First-Photo $p) 'ph-4x3' $true)</a>
    <div>
      <h2 class="section-title" id="from-the-shop">From the shop</h2>
      <h3><a href="$href">$(Enc $p.name)</a></h3>
      <p class="price">$(Money $p.price)</p>
      <p><a class="text-link" href="/shop/">Visit the shop <span aria-hidden="true">&rarr;</span></a></p>
    </div>
  </div>
</section>
"@
} else {
  $grid = '<p>Nothing in the shop right now. Check back soon.</p>'
  $homeShop = ''
}

$privacyShop = ''
if ($shopOn) { $privacyShop = $partials['privacy-shop'] }

$regions = @{
  'shop-grid'     = $grid
  'privacy-shop'  = $privacyShop
  'home-shop'     = $homeShop
  'shipping-flat' = Money $site.shopShippingFlat
  'ship-cutoff'   = Enc $site.shipCutoff
  'web3forms-key' = "<input type=""hidden"" name=""access_key"" value=""$(Enc $site.web3formsAccessKey)"">"
  'logo-1'        = $logo1
  'logo-2'        = Svg-Inline 'option-2-oval-badge.svg'
  'logo-3'        = Svg-Inline 'option-3-wordmark.svg'
  'favicon'       = Svg-Inline 'favicon.svg'
}

$skip = '\\(partials|templates|docs|content|\.git|\.claude)\\'
$pages = Get-ChildItem $Root -Recurse -Filter *.html | Where-Object { $_.FullName -notmatch $skip }
$changed = 0
foreach ($file in $pages) {
  $rel = $file.FullName.Substring($Root.Length + 1).Replace('\', '/')
  $urlPath = '/' + ($rel -replace '(^|/)index\.html$', '$1')
  $isShop = $urlPath.StartsWith('/shop/')

  if ($isShop) {
    # Shop sub-nav: mark the exact page.
    $header = $partials['shop-header']
    if ($urlPath -match '^/shop/(shipping/|returns/)?$') {
      $header = $header.Replace("href=""$urlPath"">", "href=""$urlPath"" aria-current=""page"">")
    }
    $footer = $partials['shop-footer']
  } else {
    # Main nav: mark the section the page belongs to (e.g. /contact/thank-you/ -> Request a quote).
    $header = $partials['header']
    if ($urlPath -match '^/([^/]+)/') {
      $section = "/$($Matches[1])/"
      $header = $header.Replace("href=""$section"">", "href=""$section"" aria-current=""page"">")
    }
    $footer = $partials['footer']
  }

  $head = $partials['head']
  if ($isShop -and -not $shopOn) { $head += "`n<meta name=""robots"" content=""noindex"">" }

  $html = Read-Text $file.FullName
  $new = $html
  $new = Set-Region $new 'head' $head
  $new = Set-Region $new 'header' $header
  $new = Set-Region $new 'footer' $footer
  foreach ($k in $regions.Keys) { $new = Set-Region $new $k $regions[$k] }
  if ($new -ne $html) { Write-Text $file.FullName $new; $changed++ }
}

if ($shopOn) {
  Write-Host "Built: shop ON, $($active.Count) active product(s), $($pages.Count) page(s) checked, $changed updated."
} else {
  Write-Host "Built: shop OFF (content/site.json -> shopEnabled), $($pages.Count) page(s) checked, $changed updated."
  Write-Host 'Product checks are skipped while the shop is off; turn it on to see them.'
}
if ($Warnings.Count -gt 0) {
  Write-Host ''
  Write-Host 'Still to do:' -ForegroundColor Yellow
  $Warnings | Sort-Object -Unique | ForEach-Object { Write-Host "  - $_" -ForegroundColor Yellow }
}
